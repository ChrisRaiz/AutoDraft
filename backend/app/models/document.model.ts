import { ObjectId, Schema, Connection, Model } from "mongoose";
import {
  IMetadata,
  IAccess,
  IFile,
  ICondition,
  IDynamicField,
  IDocument,
} from "../types/schema.types";
const { documentsConn } = require("../../server");

// DocumentSchema - Metadata Property
const metadataSchema = new Schema<IMetadata>(
  {
    author: { type: String, required: true }, // Name of the user
    team: { type: String, required: true }, // Name of the author's team
    createdAt: { type: Date, default: Date.now() }, // This will never change from the initial value
    updatedAt: { type: Date, default: Date.now() }, // This will update if changes are ever made to this document
  },
  { _id: false }
);

// DocumentSchema - Access Property
const accessSchema = new Schema<IAccess>(
  {
    teamId: { type: String, required: true }, // Only users part of the team with this id can access the file
    minPermissionLevel: { type: Number, default: 0 }, // 0 = all permission levels have access
  },
  { _id: false }
);

// DocumentSchema - File Property
const fileSchema = new Schema<IFile>(
  {
    name: { type: String, required: true, unique: true }, // Name of the file in R2 storage
    mimeType: { type: String, required: true }, // File format
    size: { type: Number, required: true }, // Size of the file
    url: { type: String, required: true, unique: true }, // URL to access the file
    uploadedAt: { type: Date, default: Date.now() }, // File upload date
  },
  { _id: false }
);

// DynamicFieldSchema - Conditions Property - Of
const conditionSchema = new Schema<ICondition>(
  {
    formField: { type: String, required: true }, // Form field value to check
    satisfier: { type: [String], required: true }, // Field value(s) that will satisfy the condition
  },
  { _id: false }
);

// DocumentSchema - DynamicFields Property
const dynamicFieldSchema = new Schema<IDynamicField>(
  {
    evaluation: { type: String, enum: ["all", "any"], required: true }, // How to evaluate the conditions (ALL true | ANY true)
    conditions: { type: [conditionSchema], required: true }, // Conditions for executing the method
    method: { type: String, enum: ["display", "use", "calc"], required: true }, // Method to apply
    methodProps: { type: Schema.Types.Mixed }, // Method type props (type determined via mongoose population)
  },
  { _id: false }
);

// _id property is auto-generated by mongoose
const documentSchema = new Schema<IDocument>({
  name: { type: String, required: true, unique: true }, // Name of the document in AutoDraft
  metadata: { type: metadataSchema, required: true }, // Metadata about the AutoDraft document
  access: { type: accessSchema, required: true }, // Authorized access data
  file: { type: fileSchema, required: true }, // R2 stored file data
  staticFields: {
    // Static/Unconditional fields in the document
    type: Map,
    of: String,
    required: true,
  },
  dynamicFields: {
    // Dynamic/Conditional fields in the document
    type: Map,
    of: dynamicFieldSchema,
    required: false,
  },
});

const documentsDb: Connection = documentsConn.connection.useDb("documents_db");
const Document: Model<IDocument> = documentsDb.model(
  "Document",
  documentSchema
);

module.exports = Document;
