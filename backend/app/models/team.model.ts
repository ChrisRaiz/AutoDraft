import { Schema, Connection, Model } from "mongoose";
import {
  TopDocumentStat,
  RealityTargetStat,
  DocumentGenerationStat,
  FormTurnoverStat,
  SubmissionInsightStat,
  IMember,
  ITeam,
} from "../types/schema.types";
import { ObjectId } from "mongodb";

const { usersConn } = require("../../server");

// Returns the date and time for the next payment date
async function handleNextPaymentDate(
  frequency: "never" | "monthly" | "annually"
): Promise<Date | null> {
  const nextPaymentDate = new Date();
  if (frequency == "never") {
    // Free tier
    return null;
  } else if (frequency == "monthly") {
    // Monthly subscription
    const currentMonth = nextPaymentDate.getMonth();
    nextPaymentDate.setMonth(currentMonth + 1);
  } else if (frequency == "annually") {
    // Annual subscription
    const currentYear = nextPaymentDate.getFullYear();
    nextPaymentDate.setFullYear(currentYear + 1);
  }

  return nextPaymentDate;
}

// Returns the exact time to refresh the data
function handleUpdateDate(): Date {
  const resetDate = new Date(); // Creates a Date object for the current date and time
  resetDate.setDate(resetDate.getDate() + 1); // Increments the day by 1
  resetDate.setHours(0, 0, 0, 0); // Sets the time to 00:00:00.000 (Start of day)

  return resetDate;
}

// teamSchema - member.of property
const memberSchema = new Schema<IMember>(
  {
    id: { type: Schema.Types.ObjectId, required: true }, // The user id of the team member
    name: {
      first: { type: String, lowercase: true, trim: true, required: true }, // The first name of the team member
      last: { type: String, lowercase: true, trim: true, required: true }, // The last name of the team member
    },
    permissionLevel: { type: Number, default: 3 }, // The team member's permission level
    suspended: { type: Boolean, default: false }, // Whether the team member's account is suspended
    joinedAt: { type: Date, default: Date.now() }, // When the member joined the team
    updatedAt: { type: Date, default: Date.now() }, // When the member data was last updated
  },
  { _id: false }
);

// teamSchema - statistics.submissionInsights.months.{x} property
const monthInsightSchema = new Schema<SubmissionInsightStat>(
  {
    newSubmissions: { type: Number, default: 0 }, // Number of new submissions for the month of "x"
    updatedSubmissions: { type: Number, default: 0 }, // Number of updated submissions for the month of "x"
    deletedSubmissions: { type: Number, default: 0 }, // Number of deleted submissions for the month of "x"
  },
  { _id: false }
);

// teamSchema - statistics.formTurnover.days.{x} property
const dayTurnoverSchema = new Schema<FormTurnoverStat>(
  {
    invites: { type: Number, default: 0 }, // Number of form invites sent out on the day of "x"
    responses: { type: Number, default: 0 }, // Number of form responses received on the day of "x"
  },
  { _id: false }
);

// teamSchema - statistics.documentGeneration.(prev | curr) property
const monthGenerationSchema = new Schema<DocumentGenerationStat>(
  {
    "1": { type: Number, default: 0 }, // Number of document sets generated in the 1/4 dates of the month
    "2": { type: Number, default: 0 }, // Number of document sets generated in the 2/4 dates of the month
    "3": { type: Number, default: 0 }, // Number of document sets generated in the 3/4 dates of the month
    "4": { type: Number, default: 0 }, // Number of document sets generated in the 4/4 dates of the month
  },
  { _id: false }
);

// teamSchema - statistics.realityTarget.months.{x} property
const monthTargetSchema = new Schema<RealityTargetStat>(
  {
    reality: { type: Number, default: 0 }, // The actual amount of submissions for the month of "x"
    target: { type: Number, default: 10 }, // The target amount of submissions for the month of "x"
  },
  { _id: false }
);

// teamSchema - statistics.topDocuments.docs property
const topDocumentSchema = new Schema<TopDocumentStat>(
  {
    documentSet: { type: String }, // The name of the document set
    submissions: { type: Number, default: 0 }, // The amount of form submissions for the document
    progress: { type: Number, default: 0 }, // The amount of form submissions versus the total unique generated
  },
  { _id: false }
);

// _id property is auto-generated by mongoose
const teamSchema = new Schema<ITeam>(
  {
    name: {
      type: String,
      lowercase: true,
      trim: true,
      required: true,
      unique: true,
    }, // The name of the team
    owner: {
      id: { type: Schema.Types.ObjectId, required: true }, // The user's id that owns the team
      name: {
        first: { type: String, lowercase: true, trim: true, required: true }, // The user's first name that owns the team
        last: { type: String, lowercase: true, trim: true, required: true }, // The user's last name that owns the team
      },
    },
    members: {
      // The members in the team
      type: Map,
      of: memberSchema,
      required: true,
    },
    package: {
      // The team's package/subscription details
      tier: {
        id: { type: ObjectId, required: true }, // Subscription tier id
        name: { type: String, lowercase: true, trim: true, required: true }, // Subscription tier name
      },
      fee: { type: Number, required: true }, // Subscription fee amount
      frequency: {
        // How frequent payments are due
        type: String,
        enum: ["never", "monthly", "annually"],
        lowercase: true,
        required: true,
      },
      lastPayment: { type: Date, default: Date.now() }, // Last date a payment was made
      nextPayment: { type: Date, required: false }, // Next date a payment is due
    },
    usage: {
      members: {
        available: { type: Number, default: 2 }, // Available member slots
        suspended: { type: Number, default: 0 }, // Amount of suspended members
        inUse: { type: Number, default: 1 }, // In-use member slots (unavailable)
      },
      sets: {
        storage: {
          available: { type: Number, default: 10 }, // Available document set slots
          inUse: { type: Number, default: 0 }, // In-use document set slots (unavailable)
        },
        generate: {
          available: { type: Number, default: 100 }, // Available document set generations
          used: { type: Number, default: 0 }, // Used document set generations (unavailable)
          resetAt: { type: Date, default: Date.now() }, // Date when available generations resets
        },
      },
      documents: {
        storage: {
          available: { type: Number, default: 100 }, // Available document slots
          inUse: { type: Number, default: 0 }, // In-use document slots (unavailable)
        },
      },
    },
    statistics: {
      // The team's activity statistics
      today: {
        // Today's Statistics' component data
        generatedDocs: { type: Number, default: 0 }, // Amount of document sets generated today
        newSubmissions: { type: Number, default: 0 }, // Amount of new submissions today
        submissionUpdates: { type: Number, default: 0 }, // Amount of submissions updated today
        deletedSubmissions: { type: Number, default: 0 }, // Amount of submissions deleted today
        lastUpdated: { type: Date, default: Date.now() }, // The last date any of the statistic properties were updated
        updateAt: { type: Date, default: handleUpdateDate() }, // The next date to update the values of all the statistic properties
      },
      submissionInsight: {
        // Submission Insights component data
        months: {
          jan: { type: monthInsightSchema }, // January data
          feb: { type: monthInsightSchema }, // February data
          mar: { type: monthInsightSchema }, // March data
          apr: { type: monthInsightSchema }, // April data
          may: { type: monthInsightSchema }, // May data
          jun: { type: monthInsightSchema }, // June data
          jul: { type: monthInsightSchema }, // July data
          aug: { type: monthInsightSchema }, // August data
          sep: { type: monthInsightSchema }, // September data
          oct: { type: monthInsightSchema }, // October data
          nov: { type: monthInsightSchema }, // November data
          dec: { type: monthInsightSchema }, // December data
        },
        lastUpdated: { type: Date, default: Date.now() }, // The last date the months property was updated
        updateAt: { type: Date, default: handleUpdateDate() }, // The next date to update the months property
      },
      formTurnover: {
        // Form Turnover component data
        days: {
          mon: { type: dayTurnoverSchema }, // Monday data
          tue: { type: dayTurnoverSchema }, // Tuesday data
          wed: { type: dayTurnoverSchema }, // Wednesday data
          thu: { type: dayTurnoverSchema }, // Thursday data
          fri: { type: dayTurnoverSchema }, // Friday data
          sat: { type: dayTurnoverSchema }, // Saturday data
          sun: { type: dayTurnoverSchema }, // Sunday data
        },
        lastUpdated: { type: Date, default: Date.now() }, // The last date the days property was updated
        updateAt: { type: Date, default: handleUpdateDate() }, // The next date to update the days property
      },
      documentGeneration: {
        // Document Generations component data
        prev: { type: monthGenerationSchema }, // Previous month data
        curr: { type: monthGenerationSchema }, // Current month data
        lastUpdated: { type: Date, default: Date.now() }, // The last date the prev/curr properties were updated
        updateAt: { type: Date, default: handleUpdateDate() }, // The next date to update the prev/curr properties
      },
      realityTarget: {
        // Reality vs Target component data
        months: {
          jan: { type: monthTargetSchema }, // January data
          feb: { type: monthTargetSchema }, // February data
          mar: { type: monthTargetSchema }, // March data
          apr: { type: monthTargetSchema }, // April data
          may: { type: monthTargetSchema }, // May data
          jun: { type: monthTargetSchema }, // June data
          jul: { type: monthTargetSchema }, // July data
          aug: { type: monthTargetSchema }, // August data
          sep: { type: monthTargetSchema }, // September data
          oct: { type: monthTargetSchema }, // October data
          nov: { type: monthTargetSchema }, // November data
          dec: { type: monthTargetSchema }, // December data
        },
        lastUpdated: { type: Date, default: Date.now() }, // The last date the months property was updated
        updateAt: { type: Date, default: handleUpdateDate() }, // The next date to update the months property
      },
      topDocuments: {
        // Top Documents component data
        docs: { type: [topDocumentSchema] },
        lastUpdated: { type: Date, default: Date.now() }, // The last date the docs property was updated
        updateAt: { type: Date, default: handleUpdateDate() }, // The next date to update the docs property
      },
    },
  },
  { minimize: false } // Include empty fields
);

// If package is updated, set the next payment date
teamSchema.pre("save", async function (next) {
  if (this.isModified("package")) {
    const nextPaymentDate = await handleNextPaymentDate(this.package.frequency);

    if (!nextPaymentDate && this.package.tier.id !== 0) {
      throw new Error(
        "Invalid package configuration: next payment date could not be determined."
      );
    }

    this.package.nextPayment = nextPaymentDate;
  }

  next();
});

const usersDb: Connection = usersConn.connection.useDb("users_db");
const Team: Model<ITeam> = usersDb.model("Team", teamSchema);

module.exports = Team;
